// AuthGuard 의 JIT 프로비저닝 캐시 (2026-08-11 에 파일로 분리).
//
// "이 사용자는 DB 에 있다"를 기억해 요청마다 INSERT 를 반복하지 않는다.
// **회원탈퇴가 이 기억을 지워야 한다** — 지우지 않으면 탈퇴한 사람의
// 만료 전 토큰이 캐시에 걸려 묘비 확인을 건너뛴다. 그래서 가드 안의
// private 필드가 아니라 밖에서 손댈 수 있는 자리에 둔다.
//
// 프로세스마다 따로 있는 캐시라, API 를 여러 대 띄우면 **다른 대에는
// 지웠다는 사실이 전해지지 않는다.** 다만 그 경우에도 되살아나지는
// 않는다 — 이미 캐시에 있다는 것은 INSERT 를 하지 않는다는 뜻이라,
// 남는 것은 "토큰 만료까지 빈 계정으로 보이는" 상태뿐이다.
export const knownUsers = new Set<string>();

/** 회원탈퇴가 부른다 — 다음 요청에서 묘비를 다시 확인하게 만든다 */
export function forgetKnownUser(id: string): void {
  knownUsers.delete(id);
}
