import assert from 'node:assert/strict';
import { folderTotals } from './folderTotals';
const f = (folderId: string, parentId: string | null, mapCount = 0) => ({ folderId, parentId, mapCount });
const result = folderTotals([f('education', null), f('a','education',2),f('b','a',3), f('c','b',2),f('other',null,9)]);
assert.deepEqual(result.get('education'), { maps: 7, folders: 3 });
assert.deepEqual(result.get('a'), { maps: 7, folders: 2 });
assert.deepEqual(result.get('c'), { maps: 2, folders: 0 });
assert.deepEqual(result.get('other'), { maps: 9, folders: 0 });
assert.deepEqual(folderTotals([]).size, 0);
const cycle = folderTotals([f('x','y',2),f('y','x',3),f('z','x',4)]);
assert.deepEqual(cycle.get('x'), { maps: 9, folders: 2 });
assert.deepEqual(cycle.get('y'), { maps: 9, folders: 2 });
assert.deepEqual(cycle.get('z'), { maps: 4, folders: 0 });
assert.deepEqual(folderTotals([f('self','self',1)]).get('self'), { maps: 1, folders: 0 });
assert.deepEqual(folderTotals([f('orphan','missing',5)]).get('orphan'), { maps: 5, folders: 0 });
assert.deepEqual(folderTotals([f('one',null,2),f('one',null,2)]).get('one'), { maps: 2, folders: 0 });
const deep = Array.from({length: 20000}, (_,i) => f(String(i), i ? String(i-1) : null, 1));
assert.deepEqual(folderTotals(deep).get('0'), { maps: 20000, folders: 19999 });
console.log('PASS folderTotals (12 assertions, including 20,000-level tree and cycles)');
