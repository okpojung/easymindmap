import assert from 'node:assert/strict';
import { defaultMinimapWindow, parseMinimapWindow, minimapWindowPosition as pos, moveMinimapWindow as move, nextMinimapPin, minimapWindowSize as size, resizeMinimapWindow as resize } from './minimapWindow';
const s = defaultMinimapWindow();
assert.deepEqual(pos(s, 1000, 700, 250, 210, 14), { x: 736, y: 476 });
const moved = move(s, 100, 120, 1000, 700, 250, 210, 14);
assert.deepEqual(moved.point, { x: 100, y: 120 });
assert.deepEqual(move(s, -300, 9000, 1000, 700, 250, 210, 14).point, { x: 14, y: 476 });
assert.deepEqual(pos(moved, 190, 160, 150, 100, 8), { x: 32, y: 52 });
assert.deepEqual(pos(moved, 1000, 700, 250, 210, 14), { x: 100, y: 120 });
assert.equal(nextMinimapPin('user'), 'right'); assert.equal(nextMinimapPin('right'), 'left'); assert.equal(nextMinimapPin('left'), 'user');
assert.deepEqual(pos({ ...moved, pin: 'right' }, 1000, 700, 250, 210, 14), { x: 736, y: 476 });
assert.deepEqual(pos({ ...moved, pin: 'left' }, 1000, 700, 250, 210, 14), { x: 14, y: 476 });
assert.deepEqual(move({ ...moved, pin: 'left' }, 70, 80, 1000, 700, 250, 210, 14), { ...moved, pin: 'left' });
assert.equal(move(s, NaN, 1, 1000, 700, 250, 210, 14), s);
for (const raw of [null, 'not json', '{}', 'null', '{"pin":"x"}']) assert.deepEqual(parseMinimapWindow(raw), s);
assert.deepEqual(parseMinimapWindow(JSON.stringify(moved)), moved);
assert.deepEqual(parseMinimapWindow('{"pin":"user","point":{"x":"1","y":2}}'), s);
assert.deepEqual(parseMinimapWindow('{"pin":"left","point":{"x":-5,"y":999999999999}}'), { pin: 'left', point: { x: 0, y: 1e7 } });
assert.deepEqual(pos(s, 30, 30, 80, 80, 8), { x: 0, y: 0 });
const resized = resize(moved, { w: 400, h: 300 }, moved.point!, 1000, 700, 14);
assert.deepEqual(resized, { ...moved, size: { w: 400, h: 300 } });
assert.deepEqual(move(resized, 120, 130, 1000, 700, 410, 310, 14).size, resized.size, 'moving preserves size');
assert.deepEqual(parseMinimapWindow(JSON.stringify(resized)), resized, 'new size persists');
assert.deepEqual(parseMinimapWindow('{"pin":"left","point":null,"size":{"w":9000,"h":1}}'), { pin: 'left', point: null, size: { w: 640, h: 96 } });
assert.deepEqual(parseMinimapWindow('{"pin":"right","point":null,"size":{"w":"1","h":200}}'), { pin: 'right', point: null });
assert.deepEqual(size(resized, { w: 200, h: 150 }, 320, 240, 8), { w: 294, h: 214 });
assert.deepEqual(size(resized, { w: 200, h: 150 }, 1000, 700, 14), { w: 400, h: 300 }, 'phone clamp does not erase desktop size');
assert.deepEqual(resize(moved, { w: -10, h: 1 }, moved.point!, 1000, 700, 14).size, { w: 132, h: 96 });
assert.deepEqual(resize(moved, { w: 9000, h: 9000 }, { x: 900, y: 600 }, 1000, 700, 14), { pin: 'user', point: { x: 336, y: 196 }, size: { w: 640, h: 480 } });
assert.equal(resize(resized, { w: NaN, h: 100 }, moved.point!, 1000, 700, 14), resized);
const rightSized = resize({ ...moved, pin: 'right' }, { w: 400, h: 300 }, moved.point!, 1000, 700, 14);
assert.equal(rightSized.pin, 'right'); assert.deepEqual(rightSized.point, moved.point);
assert.deepEqual(pos(rightSized, 1000, 700, 410, 310, 14), { x: 576, y: 376 });
console.log('minimap window: legacy preferences, resize limits, pin anchors, preserved size on move and responsive restoration PASS');
