import { collectMapNotes } from './mapNotes';
import { useDocumentStore } from '@/stores/documentStore';
import { buildMdTable } from '@/editor/node-renderer/TableDialog';
import { noteTableFromMd, noteTableToMd, noteTableCells } from './noteTable';
import type { SampleMap } from '@emm/model';
import assert from 'node:assert/strict';
const m = { title: 'notes', root: { id: 'root', text: 'R', notes: [{ id: 'p', type: 'paragraph', text: 'paragraph' }] }, branches: [{ id: 'A', text: 'A', collapsed: true, notes: [{ id: 'c', type: 'code_block', text: 'code', lang: 'js' }], children: [{ id: 'A1', text: 'hidden', notes: [{ id: 't', type: 'table', text: 'table' }] }] }], centers: [{ root: { id: 'C2', text: 'second', notes: [{ id: 'k', type: 'checklist', text: 'todo', checked: true }] }, branches: [] }] } as unknown as SampleMap;
assert.deepEqual(collectMapNotes(m).map((r) => [r.nodeId, r.block.id]), [['root','p'],['A','c'],['A1','t'],['C2','k']]);
console.log('PASS all types, collapsed descendants and secondary center in map order');
const st = () => useDocumentStore.getState(); st().loadMap(m, { resetHistory: true });
st().updateNoteBlock('C2', 'k', { checked: false });
assert.equal(collectMapNotes(st().map).find((r) => r.block.id === 'k')!.block.checked, false);
assert.equal(collectMapNotes(st().map).find((r) => r.block.id === 'p')!.block.text, 'paragraph');
st().addNoteBlock('A1', 'paragraph', 'new text'); assert.equal(collectMapNotes(st().map).length, 5);
st().removeNoteBlock('root', 'p'); assert.equal(collectMapNotes(st().map).length, 4);
console.log('PASS mutations target owning node without modifying other notes');
const md=buildMdTable(['','',''], [['','',''],['','','']]);
const round=noteTableCells(noteTableFromMd(md))!; assert.equal(round.rows.length + 1, 3); assert.equal(round.headers.length, 3); assert.ok(round.rows.every((r) => r.length===3));
assert.equal(noteTableCells(noteTableFromMd(noteTableToMd(noteTableFromMd(md))!))!.rows.length + 1, 3);
console.log('PASS 3x3 empty grid survives note conversion');
