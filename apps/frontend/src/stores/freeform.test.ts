import { useDocumentStore, findNodeInMap } from './documentStore';
import { computeLayout } from '@/layout/LayoutEngine';
import type { SampleMap } from '@emm/emm-parser';
const assert = (ok: unknown, label: string) => { if (!ok) throw new Error(label); };
const st = () => useDocumentStore.getState();
const sample = (): SampleMap => ({ title: 'diagram', canvasMode: 'freeform', rootPos: { dx: 0, dy: 0 }, root: { id: 'root', text: 'R', colorKey: 'root' }, branches: [{ id: 'a', text: 'A', colorKey: 'l1A', side: 'right', children: [{ id: 'b', text: 'B', layoutType: 'tree-right' }] }], centers: [{ root: { id: 'c2', text: 'C2', colorKey: 'root' }, branches: [] }], connectors: [{ id: 'edge', from: 'root', to: 'c2' }] });
for (const layout of ['radial-right', 'tree-right', 'tree-down', 'hierarchy-right', 'process-tree-right'] as const) {
  const m = sample();
  const before = computeLayout(m, layout, 800, 500);
  m.rootPos = { dx: 200, dy: -100 };
  const after = computeLayout(m, layout, 800, 500);
  const r = after.find((n) => n.id === 'root')!;
  assert(r.x === 1000 && r.y === 400, layout + ' first center normalized');
  const a = before.find((n) => n.id === 'c2')!, b = after.find((n) => n.id === 'c2')!;
  assert(a.x === b.x && a.y === b.y, layout + ' automatic extra center stationary');
}
st().loadMap(sample(), { resetHistory: true });
st().updateNodeLayoutType('a', 'radial-left');
assert(findNodeInMap(st().map, 'b')?.layoutType === 'tree-right', 'selected-only preserves descendants');
st().updateNodeLayoutType('a', 'radial-right', true);
assert(!findNodeInMap(st().map, 'b')?.layoutType, 'opt-in clears descendant overrides');
st().undo();
assert(findNodeInMap(st().map, 'b')?.layoutType === 'tree-right', 'undo restores overrides');
const history = st().past.length;
st().setCenterPos('root', { dx: 20.125, dy: -30.875 });
assert(st().map.rootPos?.dx === 20.125 && st().map.rootPos?.dy === -30.875 && st().past.length === history + 1, 'first center keeps fractional preview coordinates in one history entry');
st().setCenterPos('c2', { dx: -0.375, dy: 420.0625 });
assert(st().map.centers?.[0].pos?.dx === -0.375 && st().map.centers?.[0].pos?.dy === 420.0625, 'extra center keeps fractional coordinates');
const precisionHistory = st().past.length;
st().setCenterPos('root', { dx: NaN, dy: 0 });
st().setCenterPos('c2', { dx: 0, dy: Infinity });
assert(st().map.rootPos?.dx === 20.125 && st().map.centers?.[0].pos?.dy === 420.0625 && st().past.length === precisionHistory, 'nonfinite positions are rejected without history');
st().undo();
assert(st().map.centers?.[0].pos === undefined && st().map.rootPos?.dx === 20.125, 'undo extra center move leaves first fractional position intact');
st().redo();
assert(st().map.centers?.[0].pos?.dy === 420.0625, 'redo preserves fractional precision');
st().setCanvasMode('mindmap');
st().setCenterPos('root', { dx: 99, dy: 99 });
assert(st().map.rootPos?.dx === 20.125, 'mindmap movement blocked');
st().loadMap(sample(), { resetHistory: true });
st().deleteNode('c2');
assert(!st().map.connectors?.length, 'deleted center prunes connectors');
st().loadMap(sample(), { resetHistory: true });
st().mergeCentersInto('c2');
const edge = st().map.connectors![0];
assert(edge.to === 'root' && edge.from !== 'root' && !!findNodeInMap(st().map, edge.from), 'merged center endpoints remapped');
console.log('PASS freeform regressions');
