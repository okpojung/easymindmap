const pad2 = (n: number) => String(n).padStart(2, '0');
export const ymd = (d: Date) => `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`;

/** 표에 있는 해인가 (없으면 고정 공휴일만 안다) */
export function holidayTableCovers(year: number): boolean {
  return year in BY_YEAR;
}

/** 그 날의 공휴일 이름. 공휴일이 아니면 null */
export function holidayName(d: Date): string | null {
  const key = ymd(d);
  const fixed = FIXED.find(([m, day]) => d.getMonth() + 1 === m && d.getDate() === day);
  if (fixed) return fixed[2];
  return BY_YEAR[d.getFullYear()]?.find((h) => h.date === key)?.name ?? null;
}

/** 빨간 날 — 일요일 또는 공휴일 */
export function isRedDay(d: Date): boolean {
  return d.getDay() === 0 || holidayName(d) !== null;
}
