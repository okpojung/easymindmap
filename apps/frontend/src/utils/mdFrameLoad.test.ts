import assert from 'node:assert/strict';
import { createMdFrameLoadGate, readMdFrameSnapshot } from './mdFrameLoad';
const gate = createMdFrameLoadGate();
let flushes = 0;
const child = { MDE: { markdown: 'DEFAULT SAMPLE', getHostSnapshot(nonce: string) { if (nonce !== gate.nonce) return null; child.flushPendingEdits(); return this.markdown; } }, flushPendingEdits() { flushes++; } };
assert.equal(readMdFrameSnapshot(gate, child), null);
const first = gate.begin('# ORIGINAL');
assert.equal(readMdFrameSnapshot(gate, child), null);
assert.equal(gate.accept({ loadNonce: first, markdown: 'DEFAULT SAMPLE' }), false);
assert.equal(gate.accept({ loadNonce: 'wrong', markdown: '# ORIGINAL' }), false);
assert.equal(flushes, 0);
child.MDE.markdown = '# ORIGINAL';
assert.equal(gate.accept({ loadNonce: first, markdown: '# ORIGINAL' }), true);
assert.equal(readMdFrameSnapshot(gate, child), '# ORIGINAL');
child.flushPendingEdits = () => { child.MDE.markdown = '# JUST TYPED BEFORE DEBOUNCE'; flushes++; };
assert.equal(readMdFrameSnapshot(gate, child), '# JUST TYPED BEFORE DEBOUNCE');
gate.reset(); assert.equal(readMdFrameSnapshot(gate, child), null);
const second = gate.begin('# SECOND');
assert.notEqual(first, second);
assert.equal(gate.accept({ loadNonce: first, markdown: '# ORIGINAL' }), false);
assert.equal(gate.ready, false);
assert.equal(gate.accept({ loadNonce: second, markdown: '# SECOND' }), true);
console.log('PASS sample-before-load, mismatched/stale ACK, reload reset, immediate flush and exact load identity');

assert.equal(gate.nonce, second);
const legacyOrProtected = { MDE: { getHostSnapshot: undefined, get markdown(): string { throw new Error('Raw protected Markdown must never be read'); } }, flushPendingEdits() { throw new Error('Unbound child must never be flushed'); } };
assert.throws(() => readMdFrameSnapshot(gate, legacyOrProtected), /MD_FRAME_SNAPSHOT_UNAVAILABLE/);
assert.throws(() => readMdFrameSnapshot(gate, null), /MD_FRAME_SNAPSHOT_UNAVAILABLE/);
let passedNonce: string | null = null;
const safeProtected = { MDE: { getHostSnapshot(nonce: string) { passedNonce = nonce; return null; }, get markdown(): string { throw new Error('Protected plaintext read'); } } };
assert.equal(readMdFrameSnapshot(gate, safeProtected), null);
assert.equal(passedNonce, second);
const nonText = { MDE: { getHostSnapshot() { return { markdown: 'Not a valid protocol snapshot' }; } } };
assert.throws(() => readMdFrameSnapshot(gate, nonText), /MD_FRAME_SNAPSHOT_UNAVAILABLE/);
const staleGate = { ready: true, nonce: first };
assert.equal(readMdFrameSnapshot(staleGate, child), null);
gate.reset();
assert.equal(gate.nonce, null);
assert.equal(readMdFrameSnapshot(gate, child), null);
assert.equal(readMdFrameSnapshot({ ready: true }, child), null);
console.log('PASS nonce-bound safe capture, protected/unbound refusal, no raw plaintext/flush fallback, stale/reset boundaries');
